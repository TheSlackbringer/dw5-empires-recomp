void testInstallState(const fs::path &tempDir)
{
    std::cout << "[TEST] testInstallState..." << std::endl;
    fs::path dataDir = tempDir / "test_player_data";
    std::error_code ec;
    fs::remove_all(dataDir, ec);

    std::string prob;
    CHECK(installState(dataDir, &prob) == InstallState::Missing);

    // Create marker without xex -> Incomplete
    std::string err;
    CHECK(writeInstallMarker(dataDir, kExpectedDiscSha1, err));
    CHECK(installState(dataDir, &prob) == InstallState::Incomplete);

    // Create dummy default.xex -> Installed
    fs::create_directories(dataDir / "game" / "files", ec);
    std::ofstream xex(dataDir / "game" / "files" / "default.xex");
    xex << "DUMMY_XEX_DATA";
    xex.close();
    CHECK(installState(dataDir, &prob) == InstallState::Installed);

    std::cout << "  -> PASS\n";
}

void testResetBuildIfMoved(const fs::path &tempDir)
{
    std::cout << "[TEST] testResetBuildIfMoved..." << std::endl;
    fs::path buildDir = tempDir / "test_build";
    fs::path srcDir1 = tempDir / "source_release_v1" / "app";
    fs::path srcDir2 = tempDir / "source_release_v2" / "app";

    std::error_code ec;
    fs::create_directories(buildDir, ec);
    fs::create_directories(srcDir1, ec);
    fs::create_directories(srcDir2, ec);

    // Simulate CMakeCache.txt pointing to srcDir1
    std::ofstream cache(buildDir / "CMakeCache.txt");
    cache << "# Generated by CMake\n";
    cache << "CMAKE_HOME_DIRECTORY:INTERNAL=" << srcDir1.generic_string() << "\n";
    cache << "SOME_VAR:STRING=value\n";
    cache.close();
    fs::create_directories(buildDir / "CMakeFiles", ec);

    // Test with matching source dir -> Should NOT reset
    CHECK(!resetBuildIfMoved(buildDir, srcDir1));
    CHECK(fs::exists(buildDir / "CMakeCache.txt"));

    // Test with different source dir (release moved) -> MUST reset (commit b350108)
    CHECK(resetBuildIfMoved(buildDir, srcDir2));
    CHECK(!fs::exists(buildDir / "CMakeCache.txt"));
    CHECK(!fs::exists(buildDir / "CMakeFiles"));

    // Test with release version mismatch (built-from.txt != BUILD_ID) -> MUST reset
    std::ofstream cache2(buildDir / "CMakeCache.txt");
    cache2 << "CMAKE_HOME_DIRECTORY:INTERNAL=" << srcDir1.generic_string() << "\n";
    cache2.close();
    fs::create_directories(buildDir / "CMakeFiles", ec);
    std::ofstream(srcDir1.parent_path() / "BUILD_ID") << "v2\n";
    std::ofstream(buildDir / "built-from.txt") << "v1\n";
    CHECK(resetBuildIfMoved(buildDir, srcDir1));
    CHECK(!fs::exists(buildDir / "CMakeCache.txt"));
    fs::remove(srcDir1.parent_path() / "BUILD_ID", ec);
    fs::remove(buildDir / "built-from.txt", ec);

    // Test with toolchain sysroot present but missing from cache -> MUST reset
    std::ofstream cache3(buildDir / "CMakeCache.txt");
    cache3 << "CMAKE_HOME_DIRECTORY:INTERNAL=" << srcDir1.generic_string() << "\n";
    cache3.close();
    fs::create_directories(buildDir / "CMakeFiles", ec);
    fs::create_directories(srcDir1.parent_path() / "tools" / "clang" / "sysroot", ec);
    CHECK(resetBuildIfMoved(buildDir, srcDir1));
    CHECK(!fs::exists(buildDir / "CMakeCache.txt"));

    // Test with toolchain sysroot present and present in cache -> Should NOT reset
    std::ofstream cache4(buildDir / "CMakeCache.txt");
    cache4 << "CMAKE_HOME_DIRECTORY:INTERNAL=" << srcDir1.generic_string() << "\n";
    cache4 << "CMAKE_SYSROOT:PATH=/some/sysroot\n";
    cache4.close();
    fs::create_directories(buildDir / "CMakeFiles", ec);
    CHECK(!resetBuildIfMoved(buildDir, srcDir1));
    CHECK(fs::exists(buildDir / "CMakeCache.txt"));

    std::cout << "  -> PASS\n";
}

void testRealDiscIfPresent()
{
    fs::path isoPath = "/home/slack/Projects/dw5e-port/game/dw5e.iso";
    if (!fs::exists(isoPath))
    {
        std::cout << "[TEST] testRealDiscIfPresent skipped (no game/dw5e.iso present)\n";
        return;
    }

    std::cout << "[TEST] testRealDiscIfPresent on " << isoPath << "..." << std::endl;
    uint64_t base = 0;
    std::string err;
    bool checked = checkDiscImage(isoPath, base, err);
    CHECK(checked);
    CHECK(base == 0xFD90000ULL); // European PAL XGD2 partition offset

    std::vector<XdvdfsEntry> entries;
    bool listed = listXdvdfsFiles(isoPath, entries, err);
    CHECK(listed);
    CHECK(!entries.empty());

    bool foundXex = false;
    for (const auto &e : entries)
    {
        if (e.path == "default.xex")
            foundXex = true;
    }
    CHECK(foundXex);
    std::cout << "  -> Found " << entries.size() << " files on disc (XGD2 base 0x"
              << std::hex << base << std::dec << ")\n";

    std::cout << "  -> PASS\n";
}

