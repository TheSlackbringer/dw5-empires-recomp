#include "codegen.h"
#include "run_process.h"

#include <chrono>
#include <fstream>
#include <thread>

namespace dw5e::setup {

namespace fs = std::filesystem;

namespace {
std::string toTomlPath(const fs::path &p)
{
    std::string s = p.generic_string();
    return s;
}
} // namespace

bool generateCode(const fs::path &root,
                  const fs::path &recompiler,
                  const fs::path &logDir,
                  const std::function<bool(double fraction, const std::string &detail)> &progress,
                  std::string &error,
                  const fs::path &dataDir,
                  const std::atomic<bool> *cancel)
{
    std::error_code ec;
    fs::path effectiveData = dataDir.empty() ? root : dataDir;
    fs::path gameFiles = effectiveData / "game" / "files";
    fs::path outDir = effectiveData / "generated" / "default";

    fs::create_directories(outDir, ec);
    fs::create_directories(logDir, ec);

    // Verify input xex exists
    fs::path xex = gameFiles / "default.xex";
    if (!fs::exists(xex, ec))
    {
        error = "extracted game file default.xex not found in " + gameFiles.string();
        return false;
    }

    // Config path resolution
    fs::path configDir = root / "app" / "config";
    if (!fs::exists(configDir, ec))
        configDir = root / "config";

    fs::path manifestPath = effectiveData / "dw5e_manifest.toml";
    std::ofstream mf(manifestPath, std::ios::trunc);
    if (!mf)
    {
        error = "cannot create generated manifest " + manifestPath.string();
        return false;
    }

    mf << "# Auto-generated by DW5E Setup Wizard\n";
    mf << "[project]\n";
    mf << "name = \"dw5e\"\n";
    mf << "sdk_version = \"0.10.0\"\n";
    mf << "game_root = \"" << toTomlPath(gameFiles) << "\"\n\n";
    mf << "[entrypoint]\n";
    mf << "file_path = \"" << toTomlPath(xex) << "\"\n";
    mf << "out_directory_path = \"" << toTomlPath(outDir) << "\"\n";
    mf << "includes = [\n";
    mf << "    \"" << toTomlPath(configDir / "functions.toml") << "\",\n";
    mf << "    \"" << toTomlPath(configDir / "trace_hooks.toml") << "\",\n";
    mf << "    \"" << toTomlPath(configDir / "camera_hooks.toml") << "\"\n";
    mf << "]\n";
    mf.close();

    fs::path logFile = logDir / "codegen.log";
    fs::remove(logFile, ec);

    if (progress)
        progress(0.1, "Starting ReXGlue recompiler...");

    std::vector<std::string> args = {"codegen", manifestPath.string()};
    ProcessResult res;
    std::vector<std::pair<std::string, std::string>> env;
#ifndef _WIN32
    std::string ldLibPath;
    for (const auto &p : {root / "tools", root / "usr" / "lib", root / "tools" / "clang" / "lib", root / "rexglue-sdk" / "out" / "linux-amd64"})
    {
        if (!p.empty() && fs::exists(p, ec))
        {
            if (!ldLibPath.empty())
                ldLibPath += ":";
            ldLibPath += p.string();
        }
    }
    if (const char *curr = std::getenv("LD_LIBRARY_PATH"))
    {
        if (*curr)
        {
            if (!ldLibPath.empty())
                ldLibPath += ":";
            ldLibPath += curr;
        }
    }
    if (!ldLibPath.empty())
        env.emplace_back("LD_LIBRARY_PATH", ldLibPath);
#endif

    std::atomic<bool> done{false};
    std::thread worker([&] {
        res = runProcess(recompiler, args, root, logFile, cancel, env);
        done = true;
    });

    double currentProgress = 0.15;
    while (!done)
    {
        std::this_thread::sleep_for(std::chrono::milliseconds(250));
        if (progress)
        {
            if (currentProgress < 0.90)
                currentProgress += 0.05;
            if (!progress(currentProgress, "Translating Xenon PowerPC to C++..."))
            {
                // User cancelled
                if (cancel)
                {
                    // cancel handled by worker process
                }
            }
        }
    }
    worker.join();

    if (res.cancelled)
    {
        error = "cancelled by user";
        return false;
    }

    if (!res.started || !res.error.empty())
    {
        error = res.error.empty() ? "failed to start ReXGlue recompiler" : res.error;
        error += "; check " + logFile.string();
        return false;
    }
    if (res.exitCode != 0)
    {
        error = "ReXGlue codegen failed (exit code " + std::to_string(res.exitCode) + "); check " + logFile.string();
        return false;
    }

    if (!fs::exists(outDir / "sources.cmake", ec) && !fs::exists(outDir / "dw5e_pch.h", ec))
    {
        error = "codegen completed but generated files are missing in " + outDir.string();
        return false;
    }

    if (progress)
        progress(1.0, "ReXGlue translation complete.");

    return true;
}

} // namespace dw5e::setup
