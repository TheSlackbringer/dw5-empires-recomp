#!/usr/bin/env python3
"""Find code addresses referenced from data (vtables, function-pointer tables)
that codegen did not register as functions.

usage: find_missing_funcs.py default.pe dw5e_register.cpp [functions.toml-out]
"""
import re
import struct
import sys

BASE = 0x82000000
BLR = 0x4E800020
NOP = 0x60000000


def sections(img):
    e = struct.unpack_from("<I", img, 0x3C)[0]
    nsec = struct.unpack_from("<H", img, e + 6)[0]
    opt = struct.unpack_from("<H", img, e + 20)[0]
    s = e + 24 + opt
    for _ in range(nsec):
        name = img[s:s + 8].rstrip(b"\0").decode()
        vsize, vaddr = struct.unpack_from("<II", img, s + 8)
        flags = struct.unpack_from("<I", img, s + 36)[0]
        yield name, BASE + vaddr, vsize, bool(flags & 0x20)
        s += 40


def word(img, addr):
    return struct.unpack_from(">I", img, addr - BASE)[0]


def main():
    img = open(sys.argv[1], "rb").read()
    registered = {int(m, 16) for m in re.findall(r"0x(82[0-9A-Fa-f]{6})", open(sys.argv[2]).read())}
    secs = list(sections(img))
    code = [(va, va + size) for name, va, size, is_code in secs if is_code]
    in_code = lambda a: any(lo <= a < hi for lo, hi in code)

    refs = {}
    for name, va, size, is_code in secs:
        if is_code or name in (".pdata", ".reloc", ".XBLD", ".idata"):
            continue
        for a in range(va, va + size - 3, 4):
            v = word(img, a)
            if v % 4 == 0 and in_code(v) and v not in registered:
                refs.setdefault(v, []).append(a)

    missing = []
    for target, sources in sorted(refs.items()):
        prev = word(img, target - 4)
        # Plausible function start: previous word ends a function or is padding
        prev_is_end = prev in (BLR, 0, NOP) or (prev >> 26) == 18  # blr / pad / nop / unconditional b
        # Only trust pointers that come in tables (another code pointer next to them)
        in_table = any(in_code(word(img, s - 4)) or in_code(word(img, s + 4)) for s in sources)
        if prev_is_end and in_table:
            missing.append((target, sources))

    print(f"registered functions: {len(registered)}")
    print(f"unregistered code pointers in data: {len(refs)}; plausible function starts in tables: {len(missing)}")
    for target, sources in missing:
        print(f"  0x{target:08X}  refs {len(sources)} (first @0x{sources[0]:08X})")

    if len(sys.argv) > 3:
        with open(sys.argv[3], "w") as out:
            out.write("# Generated by tools/find_missing_funcs.py: code pointers in data tables\n")
            out.write("# that codegen did not register. Size left to codegen (0 = auto).\n[functions]\n")
            for target, sources in missing:
                out.write(f'"0x{target:08X}" = {{}}  # {len(sources)} ref(s), first @0x{sources[0]:08X}\n')
        print(f"wrote {len(missing)} entries to {sys.argv[3]}")


if __name__ == "__main__":
    main()
